// JavaScript Variables Practice

// 1. Using let
let name = "Farzana";
let age = 20;

console.log(name);
console.log(age);

// 2. Changing a let variable
let score = 50;

console.log(score);

score = 90;

console.log(score);

// 3. Using const
const university = "Southeast University";

console.log(university);

// 4. Multiple variables
let city = "Dhaka";
let department = "CSE";
let semester = 9;

console.log(city);
console.log(department);
console.log(semester);

